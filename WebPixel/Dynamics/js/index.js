// Login JS
$(document).ready(function(){
    $("#subrmit-login").click(function(){
        Login();
    });

    $("#pz-login-uname").on('keypress',function(e) {
        if(e.which == 13) {
            Login();
        }
    });

    $("#pz-login-pass").on('keypress',function(e) {
        if(e.which == 13) {
            Login();
        }
    });

    // Evento Enter
    // Login();

    function Login() {
        var uname = $("#pz-login-uname").val();
        var pass = $("#pz-login-pass").val();
        if( uname != "" && pass != "" ){
            $.post("/",
                {
                    login_username: '' + uname,
                    login_password: '' + pass
                },
                function(data){
                     var res = $.parseJSON(data);
                    if(res.result == true){
                        $("#e-login-message" ).hide("slow");
                        $("#login-message" ).show("slow");
                        $("#login-msg").html(res.msg);
                        console.log("[RDP] -> Usuario [" + uname + "] ha iniciado sesión correctamente, redireccionando en 3 segundos...");
                        setTimeout(function(){ window.location = "/me"; }, 1);
                    } else {
                        $("#e-login-message" ).hide("slow");
                        $("#e-login-msg").html(res.msg);
                        $("#e-login-message" ).show("slow");
                        console.log("[RDP] -> " + res.msg);
                    }
                });
        } else {
            $("#e-login-message" ).show("slow");
            $("#e-login-msg").html("¡Debes llenar todos los campos!");
        }
    }
});


// Register JS
$(document).ready(function(){
    $("#subrmit-register").click(function(){
        Register();
    });
    $("#register-username").on('keypress',function(e) {
        if(e.which == 13) {
            Register();
        }
    });

    $("#register-password").on('keypress',function(e) {
        if(e.which == 13) {
            Register();
        }
    });

    $("#register-password-confirm").on('keypress',function(e) {
        if(e.which == 13) {
            Register();
        }
    });

    $("#email").on('keypress',function(e) {
        if(e.which == 13) {
            Register();
        }
    });

    function Register() {

        var username = $("#register-username").val();
        var password = $("#register-password").val();
        var password_confirm = $('#register-password-confirm').val();
        var email = $("#email").val();

        $("#e-login-message" ).hide( "slow");
        $("#e-register-message" ).hide( "slow");

        if( username != "" && password != "" && password_confirm != "" && email != ""){
            if(password == password_confirm){
                $.post("/",
                    {
                        reg_username: '' + username,
                        reg_password: '' + password,
                        reg_mail: '' + email
                    },
                    function(data){
                        var res = $.parseJSON(data);
                        if(res.result == true){
                            $("#e-register-message" ).hide( "slow");
                            $("#register-message" ).show( "slow");
                            $("#register-msg").html(res.msg);
                            console.log("[RDP] -> Usuario [" + username + "] se ha registrado correctamente, redireccionando en 3 segundos...");
                            setTimeout(function(){ window.location = "/me?newuser=true"; }, 2000);
                        } else {
                            $("#e-register-message" ).show( "slow");
                            $("#e-register-msg").html(res.msg);
                            console.log("[RDP] -> " + res.msg);
                        }
                    });
            } else {
                $("#e-register-message" ).show( "slow");
                $("#e-register-msg").html("Tus contraseñas no coinciden.");
            }

        } else {
            $("#e-register-message" ).show("slow");
            $("#e-register-msg").html("¡Debes llenar todos los campos!");
        }

    }
});

